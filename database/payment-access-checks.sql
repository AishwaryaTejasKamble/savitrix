begin;
select set_config('savitrix.admin',(select user_id::text from public.savitrix_admins limit 1),true);
select set_config('savitrix.teacher',(select id::text from auth.users where id not in(select user_id from public.savitrix_admins) limit 1),true);
-- Avoid changing existing entitlements outside this rollback-only test.
delete from public.savitrix_team_access where user_id=current_setting('savitrix.teacher')::uuid;
update public.savitrix_purchases set revoked_at=now() where user_id=current_setting('savitrix.teacher')::uuid;
set local role authenticated;
select set_config('request.jwt.claim.sub',current_setting('savitrix.teacher'),true);
do $$ begin
 if public.savitrix_has_full_access() then raise exception 'Free account has full access';end if;
 if (select count(*) from public.savitrix_prompt_content)<>8 then raise exception 'Free account must see exactly eight prompt bodies';end if;
 if exists(select 1 from public.savitrix_prompt_content where not is_free) then raise exception 'Paid body leaked';end if;
 begin insert into public.savitrix_team_access(user_id) values(auth.uid());raise exception 'Self-grant allowed';exception when insufficient_privilege then null;end;
 begin perform public.savitrix_grant_team_access('cartogift@gmail.com');raise exception 'Non-admin team grant allowed';exception when insufficient_privilege then null;end;
 if has_table_privilege('authenticated','public.savitrix_purchases','INSERT') or has_table_privilege('authenticated','public.savitrix_checkout_orders','UPDATE') or has_function_privilege('authenticated','public.savitrix_finalize_test_payment(text,text)','EXECUTE') then raise exception 'Browser can fake a purchase';end if;
 if has_table_privilege('anon','public.savitrix_prompt_content','SELECT') then raise exception 'Anonymous content leaked';end if;
end $$;
select set_config('request.jwt.claim.sub',current_setting('savitrix.admin'),true);
do $$ begin if (select count(*) from public.savitrix_prompt_content)<>241 then raise exception 'Owner not fully entitled';end if;end $$;
insert into public.savitrix_team_access(user_id) values(current_setting('savitrix.teacher')::uuid);
select set_config('request.jwt.claim.sub',current_setting('savitrix.teacher'),true);
do $$ begin if (select count(*) from public.savitrix_prompt_content)<>241 then raise exception 'Complimentary account not fully entitled';end if;end $$;
reset role;
update public.savitrix_team_access set expires_at=now()-interval '1 minute' where user_id=current_setting('savitrix.teacher')::uuid;
set local role authenticated;
select set_config('request.jwt.claim.sub',current_setting('savitrix.teacher'),true);
do $$ begin if (select count(*) from public.savitrix_prompt_content)<>8 then raise exception 'Expired team account retained access';end if;end $$;
reset role;
insert into public.savitrix_checkout_orders(order_id,user_id,plan_id,amount_paise,duration_days) values('order_test_rls',current_setting('savitrix.teacher')::uuid,'teacher-library',100,30);
set local role service_role;
select set_config('savitrix.test_expiry',public.savitrix_finalize_test_payment('order_test_rls','pay_test_rls')::text,true);
do $$ begin if public.savitrix_finalize_test_payment('order_test_rls','pay_test_rls')::text<>current_setting('savitrix.test_expiry') then raise exception 'Replay extended entitlement';end if;end $$;
set local role authenticated;
select set_config('request.jwt.claim.sub',current_setting('savitrix.teacher'),true);
do $$ begin if (select count(*) from public.savitrix_prompt_content)<>241 then raise exception 'Verified test purchase did not unlock';end if;end $$;
reset role;
update public.savitrix_purchases set expires_at=now()-interval '1 minute' where payment_id='pay_test_rls';
set local role authenticated;
select set_config('request.jwt.claim.sub',current_setting('savitrix.teacher'),true);
do $$ begin if (select count(*) from public.savitrix_prompt_content)<>8 then raise exception 'Expired paid access retained';end if;end $$;
rollback;
select 'Eight free prompts, owner/team/purchased access, expiry, replay safety and denial checks passed' as result;
